-- Fonte: tabela de municípios da Receita Federal (códigos próprios RF, não IBGE 7 dígitos)

-- 1. Adiciona coluna de backup
ALTER TABLE leads_rf ADD COLUMN IF NOT EXISTS municipio_cod TEXT;

-- 2. Faz backup do código original (só se ainda não foi convertido)
UPDATE leads_rf
SET municipio_cod = municipio
WHERE municipio_cod IS NULL AND municipio ~ '^\d+$';

